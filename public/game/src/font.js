export const GLYPHS = {};
for (const [ch, s] of Object.entries(G)) {
  GLYPHS[ch] = s.split('|').map((row) => [...row].map((c) => c === '#'));
}

export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Width in pixels of text at a given scale (1px letter gap). */
export function textWidth(text, scale = 1) {
  return text.length ? (text.length * (GLYPH_W + 1) - 1) * scale : 0;
}

/** List of lit pixel coordinates for text, origin top-left, used by pyro. */
export function textPixels(text, scale = 1) {
  const pts = [];
  [...text.toUpperCase()].forEach((ch, i) => {
    const g = GLYPHS[ch] || GLYPHS['?'];
    for (let y = 0; y < GLYPH_H; y++)
      for (let x = 0; x < GLYPH_W; x++)
        if (g[y][x])
          for (let sy = 0; sy < scale; sy++)
            for (let sx = 0; sx < scale; sx++)
              pts.push({ x: (i * (GLYPH_W + 1) + x) * scale + sx, y: y * scale + sy });
  });
  return pts;
}

/** Draw text with optional 1px drop shadow. align: 'left'|'center'|'right'. */
export function drawText(ctx, text, x, y, color, { scale = 1, shadow = null, align = 'left' } = {}) {
  text = String(text).toUpperCase();
  const w = textWidth(text, scale);
  let ox = align === 'center' ? Math.round(x - w / 2) : align === 'right' ? x - w : x;
  const paint = (dx, dy, c) => {
    ctx.fillStyle = c;
    [...text].forEach((ch, i) => {
      const g = GLYPHS[ch] || GLYPHS['?'];
      for (let gy = 0; gy < GLYPH_H; gy++)
        for (let gx = 0; gx < GLYPH_W; gx++)
          if (g[gy][gx])
            ctx.fillRect(ox + dx + (i * (GLYPH_W + 1) + gx) * scale, y + dy + gy * scale, scale, scale);
    });
  };
  if (shadow) paint(scale, scale, shadow);
  paint(0, 0, color);
}
